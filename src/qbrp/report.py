"""Run all experiments and write CSVs, a Markdown report and optional figures.

The report contains no timestamps, so running the same command twice with the
same library versions produces byte-identical files.
"""

from __future__ import annotations

import math
import platform
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from . import __version__
from .experiments import (
    REGIMES,
    STRATEGIES,
    compare_strategies,
    fee_lag_sensitivity,
    ma_grid,
    overfitting_example,
    overfitting_study,
    summarise_comparison,
    summarise_overfitting,
)


@dataclass(frozen=True)
class ExperimentConfig:
    n_seeds: int = 200
    n_bars: int = 2520
    fee_bps: float = 1.0
    execution_lag: int = 1
    base_seed: int = 0
    example_seed: int | None = None  # None: the path with the median best in-sample Sharpe


def _fmt(v: object, kind: str) -> str:
    if isinstance(v, np.generic):
        v = v.item()
    if isinstance(v, float) and math.isnan(v):
        return "-"
    if kind == "pct":
        return f"{v:.0%}" if isinstance(v, float) else str(v)
    if kind == "pct1":
        return f"{v:.1%}"
    if kind == "f2":
        return f"{v:.2f}"
    if kind == "f1":
        return f"{v:.1f}"
    return str(v)


def markdown_table(df: pd.DataFrame, formats: dict[str, str] | None = None) -> str:
    formats = formats or {}
    header = "| " + " | ".join(df.columns) + " |"
    numeric = {c: pd.api.types.is_numeric_dtype(df[c]) for c in df.columns}
    sep = "|" + "|".join("---:" if numeric[c] else "---" for c in df.columns) + "|"
    lines = [header, sep]
    for i in range(len(df)):
        cells = [_fmt(df[c].iloc[i], formats.get(c, "")) for c in df.columns]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def run_all(out_dir: str | Path, cfg: ExperimentConfig | None = None, plots: bool = True):
    """Run every experiment with ``cfg`` and write results to ``out_dir``."""
    cfg = cfg or ExperimentConfig()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    runs = compare_strategies(
        n_seeds=cfg.n_seeds,
        n_bars=cfg.n_bars,
        fee_bps=cfg.fee_bps,
        execution_lag=cfg.execution_lag,
        base_seed=cfg.base_seed,
    )
    comp = summarise_comparison(runs)
    sens = fee_lag_sensitivity(n_seeds=cfg.n_seeds, n_bars=cfg.n_bars, base_seed=cfg.base_seed)
    grid = ma_grid()
    over = overfitting_study(
        n_seeds=cfg.n_seeds,
        n_bars=cfg.n_bars,
        grid=grid,
        fee_bps=cfg.fee_bps,
        execution_lag=cfg.execution_lag,
        base_seed=cfg.base_seed,
    )
    n_is = cfg.n_bars // 2
    over_sum = summarise_overfitting(over, len(grid), n_is)
    example_seed = cfg.example_seed
    if example_seed is None:
        no_edge = over[over["regime"] == "no_edge"]
        median = no_edge["best_is_sharpe"].median()
        example_seed = int(no_edge.loc[(no_edge["best_is_sharpe"] - median).abs().idxmin(), "seed"])
    ex_grid, ex_equity, ex_cut = overfitting_example(
        seed=example_seed,
        n_bars=cfg.n_bars,
        grid=grid,
        fee_bps=cfg.fee_bps,
        execution_lag=cfg.execution_lag,
    )

    float_fmt = "%.6g"
    runs.to_csv(out / "compare_runs.csv", index=False, float_format=float_fmt)
    comp.to_csv(out / "compare_summary.csv", index=False, float_format=float_fmt)
    sens.to_csv(out / "sensitivity.csv", index=False, float_format=float_fmt)
    over.to_csv(out / "overfit_runs.csv", index=False, float_format=float_fmt)
    over_sum.to_csv(out / "overfit_summary.csv", index=False, float_format=float_fmt)
    ex_grid.to_csv(out / "overfit_example_grid.csv", index=False, float_format=float_fmt)

    figures: list[str] = []
    if plots:
        try:
            from .plots import make_figures
        except ImportError:  # matplotlib is an optional extra
            figures = []
        else:
            figures = make_figures(out / "figures", runs, sens, over, ex_equity, ex_cut, ex_grid)

    (out / "report.md").write_text(
        _render(cfg, comp, sens, over_sum, ex_grid, len(grid), n_is, figures, example_seed)
    )
    return {"compare": comp, "sensitivity": sens, "overfit": over_sum, "figures": figures}


def _render(cfg, comp, sens, over_sum, ex_grid, n_trials, n_is, figures, example_seed) -> str:
    label = {k: v[0] for k, v in STRATEGIES.items()}
    years = cfg.n_bars / 252
    md: list[str] = []
    md.append("# Synthetic experiment results\n")
    md.append(
        "Generated by `qbrp experiment all` "
        f"(qbrp {__version__}, numpy {np.__version__}, pandas {pd.__version__}, "
        f"Python {platform.python_version()}). "
        f"Every number below comes from {cfg.n_seeds} simulated price paths of "
        f"{cfg.n_bars} trading days (~{years:.0f} years), seeds "
        f"{cfg.base_seed}-{cfg.base_seed + cfg.n_seeds - 1}. All strategies see the same paths. "
        f"Unless stated otherwise: fee {cfg.fee_bps:g} bp per unit turnover, execution lag "
        f"{cfg.execution_lag} bar. **These are simulated markets, not evidence about real ones.**\n"
    )
    md.append("## Regimes\n")
    for r in REGIMES.values():
        md.append(f"- `{r.name}`: {r.description}")
    md.append("")

    md.append("## 1. Strategy comparison\n")
    t = comp.copy()
    t["strategy"] = t["strategy"].map(label)
    t = t.rename(
        columns={
            "mean_sharpe": "mean Sharpe",
            "sharpe_p05": "Sharpe p5",
            "sharpe_p95": "Sharpe p95",
            "mean_cagr": "mean CAGR",
            "mean_max_drawdown": "mean max DD",
            "annual_turnover": "turnover/yr",
            "pct_sharpe_gt_0": "Sharpe>0",
            "pct_beats_bh": "beats B&H",
        }
    )
    fmts = {
        "mean Sharpe": "f2",
        "Sharpe p5": "f2",
        "Sharpe p95": "f2",
        "mean CAGR": "pct1",
        "mean max DD": "pct",
        "turnover/yr": "f1",
        "Sharpe>0": "pct",
        "beats B&H": "pct",
    }
    for regime in comp["regime"].unique():
        md.append(f"### `{regime}`\n")
        md.append(markdown_table(t[t["regime"] == regime].drop(columns="regime"), fmts))
        md.append("")
    md.append(
        "\"beats B&H\" is the share of paths on which the strategy's Sharpe exceeded "
        "buy-and-hold's Sharpe on the *same* path. The p5-p95 band shows how much a single "
        "10-year backtest can vary by luck alone.\n"
    )
    if "compare_sharpe.png" in figures:
        md.append("![Sharpe distributions](figures/compare_sharpe.png)\n")

    md.append("## 2. Fee and execution-lag sensitivity (`weak_trend`)\n")
    for strat in sens["strategy"].unique():
        s = sens[sens["strategy"] == strat]
        pivot = s.pivot(index="fee_bps", columns="execution_lag", values="mean_sharpe")
        pivot.columns = [f"lag {c}" for c in pivot.columns]
        pivot = pivot.reset_index().rename(columns={"fee_bps": "fee (bp)"})
        pivot["fee (bp)"] = pivot["fee (bp)"].map(lambda v: f"{v:g}")
        turnover = s["annual_turnover"].mean()
        md.append(f"### {label[strat]} - mean Sharpe (turnover ~{turnover:.0f}x/yr)\n")
        md.append(markdown_table(pivot, {c: "f2" for c in pivot.columns if c.startswith("lag")}))
        md.append("")
    md.append(
        f"Buy-and-hold mean Sharpe on the same paths: {sens['bh_mean_sharpe'].iloc[0]:.2f}.\n"
    )
    if "sensitivity.png" in figures:
        md.append("![Fee and lag sensitivity](figures/sensitivity.png)\n")

    md.append("## 3. Why a naive backtest misleads: choosing the best of a grid\n")
    md.append(
        f"For each path, {n_trials} long-short moving-average pairs (fast 5-50, slow 20-200) "
        f"are scored on the first half ({n_is} days) and the best is then evaluated on the "
        "second half.\n"
    )
    o = over_sum.rename(
        columns={
            "mean_best_is_sharpe": "best in-sample Sharpe",
            "mean_best_oos_sharpe": "same rule out-of-sample",
            "mean_median_oos_sharpe": "median rule out-of-sample",
            "haircut": "haircut",
            "pct_best_is_gt_1": "in-sample Sharpe>1",
            "pct_best_oos_gt_0": "OOS Sharpe>0",
            "null_expected_max_sharpe": "independent-trials bound",
        }
    )
    md.append(
        markdown_table(
            o,
            {c: "f2" for c in o.columns if c not in ("regime",)}
            | {"in-sample Sharpe>1": "pct", "OOS Sharpe>0": "pct"},
        )
    )
    md.append("")
    md.append(f"### One path in detail (`no_edge`, seed {example_seed})\n")
    if cfg.example_seed is None:
        md.append(
            "This path was chosen mechanically, not cherry-picked: its best in-sample Sharpe "
            "is the median across all paths. Top five pairs by in-sample Sharpe:\n"
        )
    top = ex_grid.head(5).copy()
    top.insert(0, "rank", range(1, len(top) + 1))
    md.append(
        markdown_table(
            top.rename(columns={"is_sharpe": "in-sample Sharpe", "oos_sharpe": "OOS Sharpe"}),
            {"in-sample Sharpe": "f2", "OOS Sharpe": "f2"},
        )
    )
    md.append("")
    if "overfit_example.png" in figures:
        md.append("![Overfitting example](figures/overfit_example.png)\n")
    if "overfit_scatter.png" in figures:
        md.append("![In-sample vs out-of-sample](figures/overfit_scatter.png)\n")
    md.append("See `docs/analysis.md` for interpretation.\n")
    return "\n".join(md)
